#!/usr/bin/env python3
"""Refresh hooks/route-table.ts from Tyler's "Frontier Model Routing" sheet (Routing tab).
Run after editing the sheet: python3 ~/.claude/mods/prompt-transform/scripts/sync-routing.py"""
import csv, io, json, urllib.request
from pathlib import Path

SHEET = "1WpP4zvX1iz_pCiPJ-CJ0Y956jJZKWgQR2Gy3Ys87zfE"
OUT = Path(__file__).resolve().parent.parent / "hooks/route-table.ts"
url = f"https://docs.google.com/spreadsheets/d/{SHEET}/gviz/tq?tqx=out:csv&sheet=Routing"
rows = list(csv.DictReader(io.StringIO(urllib.request.urlopen(url, timeout=30).read().decode())))
table = [{"id": r["task_id"], "when": f'{r["task"]}: {r["route_here_when"]}', "primary": r["primary_api_id"], "primaryEffort": r["primary_effort"],
          "value": r["value_api_id"], "valueEffort": r["value_effort"], "confidence": r["confidence"]} for r in rows if r["task_id"]]
OUT.write_text("// Generated by scripts/sync-routing.py from Tyler's Frontier Model Routing sheet (Routing tab); do not edit by hand.\n"
               f"export const ROUTING = {json.dumps(table, indent=1)} as const\n")
print(f"{len(table)} task types -> {OUT}")
